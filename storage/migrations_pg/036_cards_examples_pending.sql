-- 036 — cards.examples_pending_for：这张卡「刚蒸馏出来、还没配上对话示例」，以及当时是以哪个
-- 角色名去找的。NULL = 不待补；非空 = 待补，值就是蒸馏时用的角色名。
--
-- 蒸馏落卡时没配上对话示例就写上；角色页据此在打开这张卡时弹出编辑页，让用户自己填，或让
-- 系统重新找一次（docs/specs/examples-pending.md）。保存、重新找、关掉弹窗三个出口都置回
-- NULL —— 提醒只有蒸馏好的这一次。
--
-- 为什么连名字一起记：重新找要用蒸馏时的那个名字。卡上的 `name` 是模型写的，代码不保证它
-- 和蒸馏时指定的角色名一致。
--
-- 是行上的一列而不是 `card_json` 里的一个键：卡的内容会被原样复制到复制卡、发布的版本快照、
-- 对端同步与导出文件里，「待补」是这一行的流程状态，不是角色的内容，不该跟着走。
--
-- 只由 `set_card_examples_pending` 写；`save_card` / `update_card` 不碰这一列。
--
-- 幂等：`IF NOT EXISTS`。SQLite 孪生：101（列集锁要求两侧相等）。
-- ============================================================

ALTER TABLE cards ADD COLUMN IF NOT EXISTS examples_pending_for TEXT;
