def _chunk_paras(text, chunk_size):
    paragraphs = text.split(chr(10) + chr(10))
    chunks, cur = [], ""
    for para in paragraphs:
        if len(para) > chunk_size:
            if cur:
                chunks.append(cur); cur = ""
            for line in para.split(chr(10)):
                if len(line) > chunk_size:
                    for i in range(0, len(line), chunk_size):
                        chunks.append(line[i:i + chunk_size])
                elif len(cur) + len(line) + 1 > chunk_size and cur:
                    chunks.append(cur); cur = line
                else:
                    cur = line if not cur else cur + chr(10) + line
        elif len(cur) + len(para) + 2 > chunk_size and cur:
            chunks.append(cur); cur = para
        else:
            cur = para if not cur else cur + chr(10) + chr(10) + para
    if cur:
        chunks.append(cur)
    return chunks


def _chunk_build(name, order, frags):
    paras = [_CHUNK_VIGNETTES[o] if o in _CHUNK_VIGNETTES else o for o in order]
    sep = chr(10) + chr(10)
    text = sep.join(paras)
    chunks = _chunk_paras(text, _CHUNK_CHUNK_SIZE)
    which = []
    for f in frags:
        assert f in text, (name, 'fragment missing')
        which.append(next(i for i, c in enumerate(chunks) if f in c))
    assert len(set(which)) == len(which), (name, which)
    return text


